      // -- mod="$_calc_ch2__v_frqch2" dstVar=voice->tmp9/*pul_freq*/
      voice->tmp9/*pul_freq*/ = voice->var__calc_ch2__v_frqch2;
      voice->tmp7/*pul_speed*/ = voice->note_speed_fixed * voice->tmp9/*pul_freq*/;
      
      // ---- mod="pul" input "phase" seq 1/1
      
      // -- mod="$m_ch2_phase" dstVar=voice->tmp16/*phase*/
      voice->tmp16/*phase*/ = voice->mod_ch2_phase_cur;
      voice->tmp9/*pul_tmp*/ = ((voice->tmp15_pul_phase + voice->tmp16/*phase*/));
      voice->tmp9/*pul_tmp*/ = ffrac_s(voice->tmp9/*pul_tmp*/);
      voice->tmp6/*b*/ = (voice->tmp9/*pul_tmp*/ >= 0.5) ? 1.0f : -1.0f;
      voice->tmp15_pul_phase = ffrac_s(voice->tmp15_pul_phase + voice->tmp7/*pul_speed*/);
      voice->tmp7/*t*/ = voice->tmp2/*dly_len*/;
      
      // ---- mod="ipl" input "t" seq 1/1
      
      // -- mod="$m_lfo_shape" dstVar=voice->tmp7/*t*/
      voice->tmp7/*t*/ = voice->mod_lfo_shape_cur;
      
      // -- mod="clp" dstVar=voice->tmp7/*t*/
      if(voice->tmp7/*t*/ > 1.0f) voice->tmp7/*t*/ = 1.0f;
      else if(voice->tmp7/*t*/ < 0.0f) voice->tmp7/*t*/ = 0.0f;
