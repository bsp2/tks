      // ---- mod="dly" input "feedback" seq 1/1
      
      // -- mod="$m_fb" dstVar=voice->tmp2/*dly_fb_amt*/
      voice->tmp2/*dly_fb_amt*/ = voice->mod_fb_cur;
      out += voice->tmp3/*dly_cur*/ * voice->tmp2/*dly_fb_amt*/;
      voice->arr0_dly[voice->tmp1_dly_write_idx] = out;
      out = voice->tmp3/*dly_cur*/;
      if(++voice->tmp1_dly_write_idx >= 8192)
         voice->tmp1_dly_write_idx = 0;
      
      // -- mod="$m_ch1_level" dstVar=out
      voice->tmp2/*seq*/ = out;
      voice->tmp2/*seq*/ = voice->mod_ch1_level_cur;
      out *= voice->tmp2/*seq*/;
      
      // -- mod="set out__v_dly_l" dstVar=out
      voice->var_out__v_dly_l = out;
      
      // -- mod="rdl" dstVar=out
      out = inL;
      
      // -- mod="rdr" dstVar=out
      voice->tmp2/*seq*/ = out;
      voice->tmp2/*seq*/ = inR;
      out += voice->tmp2/*seq*/;
      
      // -- mod="0.5" dstVar=out
      out *= 0.5f;
      
      // -- mod="call _calc_ch2" dstVar=out
      // ........ template lane "_calc_ch2" modIdx=0 mod=set _calc_ch2__v_inch2
      
      // -- mod="set _calc_ch2__v_inch2" dstVar=out
      voice->var__calc_ch2__v_inch2 = out;
      
