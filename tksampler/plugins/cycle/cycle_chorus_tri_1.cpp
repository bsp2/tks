      voice->tmp3/*addsr_up*/ = voice->tmp3/*addsr_up*/ * voice->tmp3/*addsr_up*/ * voice->tmp3/*addsr_up*/;
      voice->tmp3/*addsr_up*/ *= voice->sr_factor;
      
      // ---- mod="slw" input "down" seq 1/1
      
      // -- mod="$m_slwdn" dstVar=voice->tmp5/*addsr_down*/
      voice->tmp5/*addsr_down*/ = voice->mod_slwdn_cur;
      
      // -- mod="clp" dstVar=voice->tmp5/*addsr_down*/
      if(voice->tmp5/*addsr_down*/ > 1.0f) voice->tmp5/*addsr_down*/ = 1.0f;
      else if(voice->tmp5/*addsr_down*/ < 0.0f) voice->tmp5/*addsr_down*/ = 0.0f;
      
      // -- mod="pow" dstVar=voice->tmp5/*addsr_down*/
      voice->tmp5/*addsr_down*/ = voice->tmp5/*addsr_down*/ * voice->tmp5/*addsr_down*/ * voice->tmp5/*addsr_down*/;
      voice->tmp5/*addsr_down*/ *= voice->sr_factor;
      if(voice->tmp10_slw_last < voice->tmp2/*dly_len*/)
         voice->tmp2/*dly_len*/ = voice->tmp10_slw_last + (voice->tmp2/*dly_len*/ - voice->tmp10_slw_last) * voice->tmp3/*addsr_up*/;
      else
         voice->tmp2/*dly_len*/ = voice->tmp10_slw_last + (voice->tmp2/*dly_len*/ - voice->tmp10_slw_last) * voice->tmp5/*addsr_down*/;
      voice->tmp10_slw_last = voice->tmp2/*dly_len*/;
      
      // -- mod="fma" dstVar=voice->tmp2/*dly_len*/
      voice->tmp2/*dly_len*/ = (voice->tmp2/*dly_len*/ * 0.5f) + 0.5f;
      
      // -- mod="$m_len_mod" dstVar=voice->tmp2/*dly_len*/
      voice->tmp3/*seq*/ = voice->tmp2/*dly_len*/;
      voice->tmp3/*seq*/ = voice->mod_len_mod_cur;
      
      // -- mod="clp" dstVar=voice->tmp3/*seq*/
      if(voice->tmp3/*seq*/ > 1.0f) voice->tmp3/*seq*/ = 1.0f;
      else if(voice->tmp3/*seq*/ < 0.0f) voice->tmp3/*seq*/ = 0.0f;
      
      // -- mod="0.02" dstVar=voice->tmp3/*seq*/
      voice->tmp3/*seq*/ *= 0.02f;
      voice->tmp2/*dly_len*/ *= voice->tmp3/*seq*/;
      
      // -- mod="$m_len" dstVar=voice->tmp2/*dly_len*/
      voice->tmp3/*seq*/ = voice->tmp2/*dly_len*/;
      voice->tmp3/*seq*/ = voice->mod_len_cur;
      
      // -- mod="clp" dstVar=voice->tmp3/*seq*/
      if(voice->tmp3/*seq*/ > 1.0f) voice->tmp3/*seq*/ = 1.0f;
      else if(voice->tmp3/*seq*/ < 0.0f) voice->tmp3/*seq*/ = 0.0f;
      
