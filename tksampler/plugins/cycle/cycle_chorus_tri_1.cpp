      voice->tmp3/*seq*/ *= 0.04f;
      
      // -- mod="0.0004" dstVar=voice->tmp3/*seq*/
      voice->tmp3/*seq*/ += 0.0004f;
      voice->tmp2/*dly_len*/ += voice->tmp3/*seq*/;
      voice->tmp2/*dly_len*/ *= 8192;
      voice->tmp2/*dly_len*/ = (voice->tmp2/*dly_len*/ < 1.0f) ? 1.0f : (voice->tmp2/*dly_len*/ > 8191) ? 8191 : voice->tmp2/*dly_len*/;
      voice->tmp11/*dly_read_idx*/ = voice->tmp1_dly_write_idx - (int)voice->tmp2/*dly_len*/;
      if(voice->tmp11/*dly_read_idx*/ < 0)
        voice->tmp11/*dly_read_idx*/ += 8192;
