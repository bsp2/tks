      // -- mod="slw" dstVar=voice->tmp2/*dly_len*/
      
      // ---- mod="slw" input "up" seq 1/1
      
      // -- mod="$m_slwup" dstVar=voice->tmp3/*addsr_up*/
      voice->tmp3/*addsr_up*/ = voice->mod_slwup_cur;
      
      // -- mod="clp" dstVar=voice->tmp3/*addsr_up*/
      if(voice->tmp3/*addsr_up*/ > 1.0f) voice->tmp3/*addsr_up*/ = 1.0f;
